package plugins

import (
	"os"
	"path/filepath"
	"testing"
)

func TestDigestPluginPackageMatchesTypeScriptVector(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"anypick.plugin.json":          `{"name":"acme-plugin","version":"1.0.0","apiVersion":1,"main":"index.mjs"}`,
		"index.mjs":                    "export default { activate() {} };\n",
		"lib/helper.mjs":               "export const helper = 1;\n",
		"node_modules/pkg/index.mjs":   "export const dependency = true;\n",
		"a-.txt":                       "dash",
		"a_.txt":                       "underscore",
		".git/config":                  "must be ignored",
		"__pycache__/compiled.pyc":     "must be ignored",
		"node_modules/.DS_Store":       "must be ignored",
		"node_modules/pkg/.git/config": "must be ignored",
	}
	for rel, content := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	// The expected digest below was generated by the TypeScript engine before
	// 9702015 deleted it, and is now the only record of that byte order. The
	// punctuation order also distinguishes locale-aware sorting from byte
	// sorting, and node_modules proves dependencies remain inside the pin.
	const want = "cb58c2dfb723378d38747d65afd92d769a465d579d167fee0568f06b3e8d79de"
	got, err := DigestPluginPackage(root)
	if err != nil {
		t.Fatal(err)
	}
	if got != want {
		t.Fatalf("digest = %s, want the recorded TypeScript vector %s", got, want)
	}

	if err := os.WriteFile(filepath.Join(root, "node_modules", "pkg", "index.mjs"),
		[]byte("export const dependency = false;\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	changed, err := DigestPluginPackage(root)
	if err != nil {
		t.Fatal(err)
	}
	if changed == got {
		t.Fatal("node_modules change did not invalidate package digest")
	}
}

func TestDigestPluginPackageFollowsFileSymlinkButNotDirectorySymlink(t *testing.T) {
	if os.PathSeparator == '\\' {
		t.Skip("unprivileged Windows test environments cannot create symlinks")
	}
	root := t.TempDir()
	target := filepath.Join(t.TempDir(), "target.txt")
	if err := os.WriteFile(target, []byte("v1"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, filepath.Join(root, "linked.txt")); err != nil {
		t.Fatal(err)
	}
	outsideDir := t.TempDir()
	if err := os.WriteFile(filepath.Join(outsideDir, "ignored.txt"), []byte("ignored"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outsideDir, filepath.Join(root, "linked-dir")); err != nil {
		t.Fatal(err)
	}
	before, err := DigestPluginPackage(root)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte("v2"), 0o600); err != nil {
		t.Fatal(err)
	}
	after, err := DigestPluginPackage(root)
	if err != nil {
		t.Fatal(err)
	}
	if before == after {
		t.Fatal("file symlink target bytes were not hashed")
	}
}
